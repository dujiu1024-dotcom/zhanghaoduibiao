def load():
    dirs = {}
    for fn in sorted(os.listdir(HERE)):
        if fn.startswith("data_") and fn.endswith(".py"):
            mod = importlib.import_module(fn[:-3])
            dirs.update(mod.DIRS)
    return dirs


dirs = load()
os.makedirs(OUT, exist_ok=True)
rows = []
for d in sorted(dirs):
    for r in dirs[d]["rows"]:
        rows.append([r[0], f"{d} {dirs[d]['name']}"] + list(r[1:]))

with open(os.path.join(OUT, "experience.csv"), "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f)
    w.writerow(HEADER)
    w.writerows(rows)

for d in sorted(dirs):
    name = dirs[d]["name"]
    fn = os.path.join(OUT, f"{d}-{name}.md")
    lines = [f"# 方向 {d}：{name}（{len(dirs[d]['rows'])} 条）", ""]
    lines.append("字段口径：E1 个案（单人单次、无数字，只能当假设）／E2 经验共识（≥2 个互不相关来源一致）／E3 可复现（有过程、有数字、有反例）／E4 自己实测（本项目产出，暂空）。")
    lines.append("")
    lines.append("| 编号 | 结论 | 等级 | 来源数 | 平台 | 发布日期 | 原文摘录 | 有无数字 | 反例或相反说法 |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for r in dirs[d]["rows"]:
        _, concl, lvl, n, plat, link, date, quote, num, counter = r
        vals = [r[0], concl, lvl, str(n), plat, date, quote + f"〔{link}〕", num, counter]
        vals = [v.replace("|", "／") for v in vals]
        lines.append("| " + " | ".join(vals) + " |")
    lines.append("")
    lines.append("## 本方向最缺什么、下一批去哪找")
    lines.append("")
    lines.append(NOTES.get(d, "（待补）"))
    lines.append("")
    with open(fn, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

print("dirs", sorted(dirs), "rows", len(rows))
