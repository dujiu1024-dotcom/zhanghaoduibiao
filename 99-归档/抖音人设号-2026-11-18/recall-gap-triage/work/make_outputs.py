def load_qb():
    d = {}
    for f in sorted(glob.glob(str(ACC / "题库" / "*.csv"))):
        with open(f, encoding="utf-8-sig", newline="") as fh:
            for r in csv.DictReader(fh):
                if (r.get("题号") or "").strip():
                    d[r["题号"].strip()] = r
    return d


def xilei_of(path):
    for k, v in XILEI.items():
        if path.endswith(k):
            return v
    if path.startswith("accounts/"):
        return "—（账号对标档案，无 77 格归属）"
    return "—（自撰方法论文档，无 77 格归属）"


