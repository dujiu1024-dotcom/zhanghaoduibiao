CAT_NAME = {1: "1 真缺料", 2: "2 缺入口·词汇鸿沟", 3: "3 缺入口·跨语言", 4: "4 标注问题"}


def main():
    qb = load_qb()
    rows = list(csv.DictReader(open(DETAIL, encoding="utf-8-sig", newline="")))
    cands = {}
    for line in open(CAND, encoding="utf-8"):
        o = json.loads(line)
        cands[o["题号"]] = o

    # ---- 32 题逐题表
    g32 = [r for r in rows if r["四分类"] == "不在任何一路候选"]
    out32 = []
    for r in g32:
        q = r["题号"]
        cat, why = TRIAGE[q]
        out32.append({
            "题号": q,
            "问句": qb[q]["问题原文"],
            "组": GROUPS[q[:2]],
            "细类（77格）": xilei_of(qb[q]["gold路径"]),
            "定性类别": CAT_NAME[cat],
            "依据": why,
        })
    p32 = OUT / "逐题定性-32题.csv"
    with open(p32, "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out32[0].keys()))
        w.writeheader()
        w.writerows(out32)

    # ---- 41 题归属表
    g71 = [r for r in rows if r["四分类"] == "在某路候选，融合后掉出前5"]
    g41 = [r for r in g71 if r["诊断名次"].strip() == "不在前50"]
    out41 = []
    for r in g41:
        q = r["题号"]
        lit, tag = r["字面路"].strip(), r["标签路"].strip()
        if lit != "—" or tag != "—":
            trigger = f"单路候选命中：字面#{lit} 标签#{tag}"
            real = "仅单路候选，融合未进前50（建议单列第 5 类）"
        else:
            trigger = r["备注"].split("；")[0] or "同文档其它段进候选"
            real = "不在任何一路候选（应并入原 32 题组）"
        out41.append({
            "题号": q,
            "问句": qb[q]["问题原文"],
            "组": GROUPS[q[:2]],
            "gold": f"{qb[q]['gold路径']} {qb[q]['gold段号']}".strip(),
            "诊断名次": r["诊断名次"],
            "分类触发依据": trigger,
            "真实归属": real,
        })
    p41 = OUT / "41题归属核对.csv"
    with open(p41, "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out41[0].keys()))
        w.writeheader()
        w.writerows(out41)

    from collections import Counter
    print("32 题定性分布:", Counter(x["定性类别"] for x in out32))
    print("41 题归属分布:", Counter(x["真实归属"] for x in out41))
    print("写出:", p32, p41)


if __name__ == "__main__":
    main()
