def load_clauses():
    lines = open(LOCAL, encoding="utf-8").read().splitlines()
    marks = []
    for i, l in enumerate(lines):
        m = re.match(r"^(\d+)\.\s+(.+)$", l)
        if m and 1 <= int(m.group(1)) <= 39:
            marks.append((int(m.group(1)), m.group(2).strip(), i + 1))
    out = []
    for idx, (n, title, ln) in enumerate(marks):
        end = marks[idx + 1][2] - 1 if idx + 1 < len(marks) else len(lines)
        body = [x.strip() for x in lines[ln - 1:end] if x.strip()]
        sent = ""
        for s in body:
            if any(v in s for v in ["平台禁止", "平台严禁", "平台还禁止", "平台不欢迎",
                                     "平台反对", "平台谴责", "平台要求", "必须做到"]):
                sent = s
                break
        if not sent and len(body) > 1:
            sent = body[1]
        if n in QUOTE:
            sent = QUOTE[n]
        out.append((n, title, ln, sent))
    return out


